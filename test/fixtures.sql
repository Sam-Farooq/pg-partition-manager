-- test/fixtures.sql
--
-- Tables for the suite to work on. Everything here is written by hand and
-- created inside the throwaway test database. No data in this repository came
-- from a running system, and nothing in it has been measured anywhere but in
-- the test run that produced it.

CREATE SCHEMA IF NOT EXISTS fixture;

-- A range-partitioned parent with the shape every test uses: a timestamptz
-- key called at, one bigint and one text column.
CREATE OR REPLACE FUNCTION fixture.new_parent(
    tbl           name,
    with_default  boolean DEFAULT false,
    nsp           name    DEFAULT 'public'
)
RETURNS regclass
LANGUAGE plpgsql
AS $$
BEGIN
    EXECUTE format('DROP TABLE IF EXISTS %I.%I CASCADE', nsp, tbl);
    EXECUTE format(
        'CREATE TABLE %I.%I (
             id    bigint GENERATED BY DEFAULT AS IDENTITY,
             at    timestamptz NOT NULL,
             body  text
         ) PARTITION BY RANGE (at)', nsp, tbl);

    IF with_default THEN
        EXECUTE format(
            'CREATE TABLE %I.%I PARTITION OF %I.%I DEFAULT',
            nsp, tbl || '_default', nsp, tbl);
    END IF;

    RETURN format('%I.%I', nsp, tbl)::regclass;
END $$;

-- A standalone table shaped like the parent, for the attach tests. Not a
-- partition of anything yet.
CREATE OR REPLACE FUNCTION fixture.new_orphan(
    tbl   name,
    rows  integer     DEFAULT 0,
    at    timestamptz DEFAULT '2026-04-10 12:00+00',
    nsp   name        DEFAULT 'public'
)
RETURNS regclass
LANGUAGE plpgsql
AS $$
BEGIN
    EXECUTE format('DROP TABLE IF EXISTS %I.%I CASCADE', nsp, tbl);
    EXECUTE format(
        'CREATE TABLE %I.%I (
             id    bigint GENERATED BY DEFAULT AS IDENTITY,
             at    timestamptz NOT NULL,
             body  text
         )', nsp, tbl);

    IF rows > 0 THEN
        EXECUTE format(
            'INSERT INTO %I.%I (at, body)
             SELECT $1, ''row '' || g FROM generate_series(1, $2) g',
            nsp, tbl) USING at, rows;
    END IF;

    RETURN format('%I.%I', nsp, tbl)::regclass;
END $$;

CREATE OR REPLACE FUNCTION fixture.seed(
    parent  regclass,
    at      timestamptz,
    rows    integer DEFAULT 1
)
RETURNS bigint
LANGUAGE plpgsql
AS $$
DECLARE
    inserted bigint;
BEGIN
    EXECUTE format(
        'INSERT INTO %s (at, body) SELECT $1, ''row '' || g FROM generate_series(1, $2) g',
        parent::text) USING at, rows;
    GET DIAGNOSTICS inserted = ROW_COUNT;
    RETURN inserted;
END $$;

CREATE OR REPLACE FUNCTION fixture.row_count(rel regclass)
RETURNS bigint
LANGUAGE plpgsql
STABLE
AS $$
DECLARE
    n bigint;
BEGIN
    EXECUTE format('SELECT count(*) FROM %s', rel::text) INTO n;
    RETURN n;
END $$;

-- Sequential scans recorded against a table. The caller is responsible for
-- running SELECT pg_stat_force_next_flush() as its own statement first:
-- table statistics are flushed when a transaction ends, so a count read in
-- the same transaction as the work is the count from before the work.
CREATE OR REPLACE FUNCTION fixture.seq_scans(rel regclass)
RETURNS bigint
LANGUAGE sql
STABLE
AS $$
    SELECT coalesce(seq_scan, 0) FROM pg_stat_all_tables WHERE relid = rel;
$$;

CREATE OR REPLACE FUNCTION fixture.child_names(parent regclass)
RETURNS text[]
LANGUAGE sql
STABLE
AS $$
    SELECT coalesce(array_agg(c.relname::text ORDER BY c.relname), '{}')
      FROM pg_inherits i
      JOIN pg_class c ON c.oid = i.inhrelid
     WHERE i.inhparent = parent;
$$;
